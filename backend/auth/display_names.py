"""Каноникализация публичных никнеймов.

Задача: запретить визуально одинаковые ники, набранные в разных
раскладках/алфавитах (латиница vs кириллица vs греческий), но при этом
учитывать регистр — «Тест» и «тест» считаются РАЗНЫМИ никами.

Подход: каждый символ-«двойник» отображается в латинский символ, на который
он визуально похож, регистр при этом сохраняется:
  Cyrillic 'А' -> Latin 'A', Cyrillic 'а' -> Latin 'a' и т.д.
Канонические ключи двух визуально одинаковых ников совпадают, а ники,
отличающиеся только регистром, дают разные ключи.

Дополнительно применяется NFKC-нормализация (fullwidth-символы, лигатуры).
Цифры намеренно не трогаем, чтобы не блокировать легитимные ники вида «007».
"""

import unicodedata

# Визуальные двойники -> латинский символ, на который они похожи.
# Только буквы; регистр сохраняется (заглавные -> заглавные).
_CONFUSABLES: dict[str, str] = {
    # --- Кириллица ---
    "А": "A", "а": "a",
    "В": "B", "в": "b",
    "С": "C", "с": "c",
    "Е": "E", "е": "e",
    "Ё": "E", "ё": "e",
    "Н": "H", "н": "h",
    "І": "I", "і": "i",
    "Ї": "I", "ї": "i",
    "Ј": "J", "ј": "j",
    "К": "K", "к": "k",
    "М": "M", "м": "m",
    "О": "O", "о": "o",
    "Р": "P", "р": "p",
    "Ѕ": "S", "ѕ": "s",
    "Т": "T", "т": "m",
    "Х": "X", "х": "x",
    "У": "Y", "у": "y",
    # --- Греческий ---
    "Α": "A", "α": "a",
    "Β": "B", "β": "b",
    "Ε": "E", "ε": "e",
    "Η": "H", "η": "n",
    "Ι": "I", "ι": "i",
    "Κ": "K", "κ": "k",
    "Μ": "M", "μ": "u",
    "Ν": "N", "ν": "v",
    "Ο": "O", "ο": "o",
    "Ρ": "P", "ρ": "p",
    "Τ": "T", "τ": "t",
    "Χ": "X", "χ": "x",
    "Ζ": "Z", "ζ": "z",
    "Υ": "Y", "υ": "u",
    "ω": "w",
    "Ϲ": "C", "ϲ": "c",
}


def clean_display_name(value: str) -> str:
    """NFKC + схлопывание пробелов (та же чистка, что в схеме регистрации)."""
    return " ".join(unicodedata.normalize("NFKC", value).split())


def canonicalize_display_name(value: str) -> str:
    """Канонический ключ ника для проверки уникальности.

    Регистр сохраняется: «Тест» и «тест» дают разные ключи.
    Визуально одинаковые ники из разных алфавитов
    (латинская 'A' vs кириллическая 'А') дают одинаковый ключ.
    """
    return "".join(_CONFUSABLES.get(ch, ch) for ch in clean_display_name(value))
